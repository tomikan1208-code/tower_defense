# -*- coding: utf-8 -*-
"""報酬。**勝敗が主軸。整形は「盤面の良さ」の差分だけで、総量が有界。**

なぜ作り直したか
----------------
前の版は「獲得コイン x 0.001」を毎ステップ足していた。2 人戦は収入間隔が 5 秒で、
送りの ``income_gain`` が雪だるま式に効くので 1 試合の総獲得コインが 3 万に届く。
整形だけで **+29.6** 貯まり、勝敗の ±1.0 に対して **30 倍**。方策は「勝つ」ではなく
「コインを稼ぐ」を学んでいた。塔が弓ばかりになるのも、送りが塔上限まで後回しに
なるのも、すべてこの一点の帰結だった。

同じ罠は「インカムが増えたら +」「相手のライフを削ったら +」でも必ず起きる。
**足し続けられる量をそのまま報酬にすると、整形が勝敗を追い越す。**
削り合い・送り合いが成立するこのゲームでは、両者が交互に殴るだけで無限に稼げる。

だから整形は **ポテンシャル差分** に限定した (Ng, Harada & Russell 1999)。
盤面の良さ Φ(s) をおおよそ [-1, 1] に収まるよう定義して、

    整形報酬 = γ Φ(s') − Φ(s)

を毎ステップ渡す。**割引和は端点だけで決まる**::

    Σ γ^t (γ Φ(s_{t+1}) − Φ(s_t)) = γ^T Φ(s_T) − Φ(s_0)

PPO が最適化しているのは割引リターンなので、これが効く量。つまり

- 良くなっていく途中で密に信号が来る（PPO が学習できる）
- **どれだけ長く殴り合っても、効く総量は Φ の端点の差を超えない**
  ＝ ライフやインカムの奪い合いで無限に稼ぐことが原理的にできない

ひとつ注意。**ログに出る「1 試合の報酬の単純和」は端点の差にならない。**
割り引かずに足すと ``−Φ_0 + γΦ_T − (1−γ)ΣΦ_t`` で、第 3 項ぶん漏れる。
γ=0.997 で 900 ステップなら最悪 2.7 に達するので、**単純和を見て
「整形が主軸より大きい」と判断してはいけない**（最適化されているのは割引和のほう）。
検算は :func:`selfcheck.check_reward_shaping` にある。

Φ に何を入れるか
----------------
**すべて相手との差**にしてある。自分の絶対値にすると「両者が一緒に太る」だけで
稼げてしまい、壊れたコイン報酬と同じ形になる。差なら相手の伸びで相殺される。

``life``
    自分のライフ率 − 生存している相手の平均ライフ率。
    **相手から奪えば +、自分が削られれば −**。取り返しても Φ が元へ戻るだけで、
    往復ぶんの合計は 0 になる（無限ファームができない理由）。
``income``
    インカムの相対優位。送りでインカムを伸ばす行動はここで報われる。
    両者が同じだけ伸ばしたら 0。分母に下駄を履かせて序盤の 1 差が暴れないようにする。
``threat``
    **経路踏破時の累積被ダメージの相対優位。** 基準の敵が湧き点からコアまで
    歩いたとき合計で何ダメージ受けるかを、迷路と塔をまとめて 1 つの数にしたもの。

    以前はここに「射程カバレッジ重み付き経路長」を使っていたが、あれは
    *セル数* を数えるので、氷塔は「ダメージ 3 の弱い塔」に、呪詛塔と監視塔は
    「価値 0」に見えていた。**滞在時間で積分する**と、減速はそのセルの
    滞在時間を伸ばして周りの塔のダメージをまとめて増やし、脆弱化と支援も
    そのまま乗る。実測（弓 8 基の盤面に 9 基目を足したときの 1 コインあたりの増分）::

        氷塔 17.10 > 弓塔 9.55 > 弩塔 7.42 > 呪詛塔 4.34 > 監視塔 4.21 > 砲塔 4.19

    旧指標だと弓塔 0.900 > 弩塔 0.680 > 氷塔 0.556 …… で、
    **実際に建っていた順番（弓と弩だけ）とそのまま一致していた。**

直接の罰として残したもの
------------------------
ポテンシャルにできない（片側にしか動かない・状態ではなく行動の性質）ものだけ。
いずれも 1 試合の合計で 0.1 を超えない大きさにしてある。
"""

from __future__ import annotations

from typing import Optional

import numpy as np

# ---- 主軸 ----------------------------------------------------------
WIN = 1.0
LOSE = -1.0
#: FFA の順位報酬。1 位 +1.0 / 2 位 +0.2 / 3 位 0 / 以降 -0.2
FFA_RANK_REWARD = (1.0, 0.2, 0.0)
FFA_RANK_TAIL = -0.2

# ---- ポテンシャル整形 ----------------------------------------------
#: 割引率。**``train.py`` の ``cfg.gamma`` と必ず一致させること。**
#: ずれるとポテンシャル整形の「方策を変えない」保証が崩れる。
#: 環境変数で上書きされたときのために、``train.py`` が起動時にここへ代入し直す。
#:
#: 0.997 から上げた理由
#: --------------------
#: 実効視野は ``1/(1-γ)`` 手。1 手 = 1 秒なので、
#: 0.997 では 333 手 ＝ 5.5 分しか見えない。カリキュラム最終段は 20 分
#: （1,200 手）あるので、**開幕の 1 手から見た勝敗は 0.997^1200 ≒ 2.7% まで
#: 減衰していた**。このゲームの一番大事な判断（守りに使うか、送って収入を
#: 伸ばすか）は 10 分以上先に効くので、それが視野の外にあった。
#: 0.999 なら視野 1,000 手 ＝ 16.7 分、開幕からの勝敗も 30% 残る。
GAMMA = 0.999

#: Φ の重み。合計しても主軸 (±1.0) を超えないようにする
W_LIFE = 0.60      # ライフ差。このゲームの勝敗そのもの
W_INCOME = 0.15    # インカム差。送りの見返りはここに入る
W_THREAT = 0.15    # 塔の「削り能力」の差
W_PATH = 0.10      # 経路の露出時間の差（下の注記）

#: インカム相対優位の分母に足す下駄。開幕 5 対 5 のとき 1 差で 0.09 に収まる
INCOME_FLOOR = 20.0
#: 経路露出（射程カバレッジ重み付き経路長）の下駄
PATH_FLOOR = 200.0
#: 累積被ダメージの相対優位の分母に足す下駄。
#: 開幕（両者 0）で 1 ダメージの差が暴れないようにする
THREAT_FLOOR = 300.0

# ---- 直接の罰（合計で 0.1 程度に収める） ----------------------------
#
# **遊休率の罰は廃止した。** 「射程内に敵がいない塔」の割合は、24 基に対して
# 敵が数体しかいない普通の局面でも 0.8 を超える。塔の置き方ではなく
# 「塔を建てたこと」への課税になっていて、実測で 1 試合 -3.8（主軸の 4 倍）だった。
# 経路から外れた塔を咎める役目は Φ の ``maze`` 項が果たす。
# 経路を覆わない塔は weighted_path を 1 も増やさないので、
# 罰を置かなくても「置いても得しない」が伝わる。指標としてだけ残してある。
#
#: 手札が上限のまま余している歩数。カードは 30 秒に 1 枚しか来ない。
#: **ポテンシャルではないので上限が無い**（900 歩ずっと溢れさせると -1.8）。
#: 溢れっぱなしは実際に純粋な損失なので残すが、値は小さく取る
HAND_FULL_PENALTY = -0.002
#: 空振り（マスクを通ったが「経路が塞がる」等で弾かれた手）
INVALID_ACTION = -0.002
#: 終焉騎にライフ上限を奪われた。取り返せない損失なので直接引く
MAX_LIFE_STOLEN = -0.05


def rank_reward(rank: np.ndarray, players: np.ndarray) -> np.ndarray:
    """順位に応じた終端報酬。1 対 1 はそのまま勝敗になる。"""
    out = np.full(rank.shape, FFA_RANK_TAIL, dtype=np.float32)
    for i, value in enumerate(FFA_RANK_REWARD):
        out = np.where(rank == i, value, out)
    # 2 人戦は 1 位 +1 / 2 位 -1（順位報酬ではなく勝敗）
    duel = players <= 2
    out = np.where(duel, np.where(rank == 0, WIN, LOSE), out)
    return out


def _lead(mine: np.ndarray, theirs: np.ndarray, floor: float) -> np.ndarray:
    """相対優位 (mine − theirs) / (mine + theirs + floor) を [-1, 1] で返す。

    **両者が一緒に太っても 0 になる**のが要点。自分の絶対値を報酬にすると、
    削り合い・送り合いで無限に稼げてしまう（旧報酬が壊れた形）。
    """
    return np.clip((mine - theirs) / np.maximum(mine + theirs + floor, 1e-6),
                   -1.0, 1.0)


def potential(life_ratio: np.ndarray, opp_life_ratio: np.ndarray,
              income: np.ndarray, opp_income: np.ndarray,
              threat: np.ndarray, opp_threat: np.ndarray,
              path: np.ndarray, opp_path: np.ndarray) -> np.ndarray:
    """盤面の良さ Φ(s)。**状態だけの関数**（行動や履歴を混ぜてはいけない）。

    ``threat`` と ``path`` を両方入れているのは、片方だけでは足りないと
    実測で分かったから。防衛ベンチ（同じ金・同じ波で漏れ率だけを測る）で

    - 塔の構成だけを変えた 2 つの盤面は ``threat`` で正しく差がつく
    - **迷路だけを変えた 2 つの盤面は ``threat`` がほぼ同じ値になる**
      （弓 24 基 Lv3 で経路 60.2 と 35.6 → どちらも 13,100 台。
      実際の漏れ率は 57.5% と 91.8% で 34 ポイントも違う）

    後者は ``threat`` が **敵 1 体あたりの被ダメ**を測っているため。飽和した
    盤面では「同時に狙われる敵の数」が経路の長さに比例して増えるので、
    1 体あたりで見ると経路長が式から落ちる。実戦ではそう綺麗に分配されず
    （弓は FIRST 狙いなので同じ敵に集中して過剰殺傷する）、
    経路が長いほうが明確に強い。そこを ``path`` で補っている。

    :param life_ratio: 自分のライフ / 開始ライフ
    :param opp_life_ratio: 相手の平均ライフ率（脱落者は 0 として数える）
    :param income: 自分のインカム
    :param opp_income: 相手の平均インカム
    :param threat: 敵 1 体が踏破するあいだに受ける被ダメージ
    :param opp_threat: 相手の平均
    :param path: 射程カバレッジ重み付き経路長（＝敵が撃たれ続ける長さ）
    :param opp_path: 相手の平均
    """
    life = np.clip(life_ratio - opp_life_ratio, -1.0, 1.0)
    return (W_LIFE * life
            + W_INCOME * _lead(income, opp_income, INCOME_FLOOR)
            + W_THREAT * _lead(threat, opp_threat, THREAT_FLOOR)
            + W_PATH * _lead(path, opp_path, PATH_FLOOR)).astype(np.float32)


def shaping(prev_phi: np.ndarray, phi: np.ndarray,
            gamma: Optional[float] = None) -> np.ndarray:
    """ポテンシャル差分 γΦ(s') − Φ(s)。総和は Φ の差にしかならない。

    ``gamma`` の既定値を引数に焼き込まないこと。既定引数は import 時に
    評価されるので、``train.py`` が環境変数に合わせて :data:`GAMMA` を
    代入し直しても反映されず、**整形と PPO の割引率が黙ってずれる**。
    """
    g = GAMMA if gamma is None else gamma
    return (g * phi - prev_phi).astype(np.float32)


def step_reward(shaped: np.ndarray, hand_full: np.ndarray,
                invalid: np.ndarray, max_lives_lost: np.ndarray) -> np.ndarray:
    """1 ステップぶんの途中報酬。

    :param shaped: :func:`shaping` の出力
    :param hand_full: 手札が上限のまま何も置かなかったか
    :param invalid: このステップで空振りした手の数
    :param max_lives_lost: 奪われたライフ上限
    """
    return (shaped
            + HAND_FULL_PENALTY * hand_full
            + INVALID_ACTION * invalid
            + MAX_LIFE_STOLEN * max_lives_lost).astype(np.float32)
